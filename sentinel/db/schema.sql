-- Sentinel data layer (plan section 7): contract between the Python backend (sentinel/) and the dashboard.
--
-- Apply (drops and recreates every table; demo data only):
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f sentinel/db/schema.sql
-- Needs PostgreSQL 15+ (UNIQUE NULLS NOT DISTINCT). Use the direct Aiven service URI, not the PgBouncer
-- pool: the backend LISTENs.
--
-- Notification channels:
--   cve_batch  payload 'min_id:max_id', sent by trigger once per INSERT statement into cve_events that
--              inserted at least one row (an ON CONFLICT DO NOTHING re-insert sends nothing). Delivered on
--              commit, so commit once per replay chunk. Read the batch WHERE id BETWEEN min_id AND max_id.
--   feed_done  sent by feed.py after the last chunk: SELECT pg_notify('feed_done', ''). No trigger.
--
-- Drivers: ids are integer (a JS number in node-pg). numeric comes back as Decimal (psycopg) and as a
-- string (node-pg); cast cvss::float8 in SELECTs that feed JSON.
--
-- Reset between demo runs (keeps discovered services and the threat_intel cache):
--   TRUNCATE cve_events, incidents, agent_runs, agent_log RESTART IDENTITY;
--   UPDATE services SET status = 'HEALTHY';

SET client_min_messages = warning;

BEGIN;

DO $$
BEGIN
    IF current_setting('server_version_num')::int < 150000 THEN
        RAISE EXCEPTION 'Sentinel schema needs PostgreSQL 15+, this server runs %', current_setting('server_version');
    END IF;
END
$$;

DROP VIEW IF EXISTS feed_funnel;
DROP TABLE IF EXISTS agent_log, agent_runs, incidents, threat_intel, cve_events, services CASCADE;
DROP FUNCTION IF EXISTS cve_events_notify_batch() CASCADE;


-- Inventory, upserted by scanner.py from container labels: ON CONFLICT (name) DO UPDATE everything but status.
CREATE TABLE services (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                text NOT NULL UNIQUE,      -- label sentinel.service: shop | admin-panel | billing-worker
    container_name      text NOT NULL,
    language            text NOT NULL,             -- label sentinel.language, lowercase: php | python
    runtime_version     text,                      -- live version, e.g. '8.3.30' from php -r 'echo PHP_VERSION;'
    runtime_mode        text,                      -- label sentinel.runtime_mode (PHP_SAPI): 'apache2handler' (mod_php) | 'fpm-fcgi'; NULL if not PHP
    image               text,                      -- running image, e.g. 'sentinel-shop:vulnerable', 'php:8.4.20-fpm'
    exposure            text NOT NULL DEFAULT 'internal'
                        CHECK (exposure IN ('public', 'internal')),            -- label sentinel.exposure
    monthly_revenue_eur integer NOT NULL DEFAULT 0
                        CHECK (monthly_revenue_eur >= 0),                      -- label sentinel.revenue
    repo_path           text,                      -- label sentinel.repo_path: the Dockerfile, e.g. 'target-system/shop/Dockerfile'; its directory is the PR path allowlist root
    -- HEALTHY | PATCH_PENDING (fix PR open, still serving) | OFFLINE (taken offline) | RESTORING (patched image coming up)
    status              text NOT NULL DEFAULT 'HEALTHY'
                        CHECK (status IN ('HEALTHY', 'PATCH_PENDING', 'OFFLINE', 'RESTORING')),
    last_seen           timestamptz NOT NULL DEFAULT now()
);


-- One row per CVE of the replayed NVD feed (fixtures/nvd-2026-10-21.json: 544 rows).
-- Insert with ON CONFLICT (cve_id) DO NOTHING so a second replay is a no-op.
-- cvss = base score of the newest CVSS version NVD lists (cvssMetricV40 > V31 > V30 > V2). PHP2Shell: v4.0 = 9.2
-- (security@php.net, the plan's number); NVD's own Primary v3.1 is 9.8 and would turn the demo scores into 94 / 69.
CREATE TABLE cve_events (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cve_id        text NOT NULL UNIQUE,                         -- 'CVE-2026-109618'
    published     timestamptz NOT NULL,                         -- NVD 'published' is UTC without an offset: insert it as UTC
    description   text NOT NULL DEFAULT '',                     -- English description
    cvss          numeric(3,1) CHECK (cvss BETWEEN 0 AND 10),   -- NULL when NVD has no CVSS (70 of the 544)
    cvss_version  text,                                         -- '4.0' | '3.1' | '3.0' | '2.0'
    cpes          jsonb NOT NULL DEFAULT '[]',                  -- raw NVD cve.configurations: [{nodes: [{operator, negate, cpeMatch: [...]}]}]
    keyword_match boolean NOT NULL DEFAULT false,               -- description mentions an inventory language (\bphp\b): "naive keyword alerts" (40)
    -- NEW (inserted, not triaged) | CANDIDATE (keyword only, waiting for the Triage agent)
    -- | DISMISSED (not our runtime, see triage_reason) | MATCHED (CPE vendor:product matches the inventory)
    triage_status text NOT NULL DEFAULT 'NEW'
                  CHECK (triage_status IN ('NEW', 'CANDIDATE', 'DISMISSED', 'MATCHED')),
    triage_reason text,
    component     text,                                         -- set when MATCHED: affected runtime, same vocabulary as services.language ('php')
    received_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX cve_events_triage_status_idx ON cve_events (triage_status);
CREATE INDEX cve_events_component_idx ON cve_events (component) WHERE component IS NOT NULL;
CREATE INDEX cve_events_published_idx ON cve_events (published);

CREATE FUNCTION cve_events_notify_batch() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    first_id integer;
    last_id  integer;
BEGIN
    SELECT min(id), max(id) INTO first_id, last_id FROM new_rows;
    IF first_id IS NOT NULL THEN
        PERFORM pg_notify('cve_batch', first_id || ':' || last_id);
    END IF;
    RETURN NULL;
END
$$;

CREATE TRIGGER cve_events_notify_batch
    AFTER INSERT ON cve_events
    REFERENCING NEW TABLE AS new_rows
    FOR EACH STATEMENT
    EXECUTE FUNCTION cve_events_notify_batch();


-- Threat Intel agent output. data = ThreatIntel JSON: cvss, exploitation_reported, exploitation_evidence,
-- high_risk_runtime_modes, fixed_versions {branch: {version, source_url}}, unsupported_branches, conflicts, sources.
-- Cache: reuse the newest row for the component. Survives demo resets.
CREATE TABLE threat_intel (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    component  text NOT NULL,                  -- 'php'
    cve_ids    text[] NOT NULL,                -- {CVE-2026-109618,CVE-2026-109619}
    data       jsonb NOT NULL,
    fetched_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX threat_intel_component_idx ON threat_intel (component, fetched_at DESC);


-- One row per (advisory component, service), upserted by compute_danger_score:
-- ON CONFLICT (component, service_id) DO UPDATE. Every service gets a row, including score 0 / NONE.
CREATE TABLE incidents (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    component       text NOT NULL,                                     -- 'php'
    cve_ids         text[] NOT NULL DEFAULT '{}',
    service_id      integer NOT NULL REFERENCES services (id) ON DELETE CASCADE,
    danger_score    integer CHECK (danger_score BETWEEN 0 AND 100),    -- rounded final score (91.8 -> 92); NULL until scored
    score_breakdown jsonb NOT NULL DEFAULT '{}',                       -- points per factor, e.g. {"severity": 36.8, "exploitation": 20, "exposure": 20, ...}
    -- TAKE_OFFLINE (>= 80) | PR_ONLY (50-79, alert) | DIGEST (1-49, PR, no alert) | NONE (0, not affected)
    band            text CHECK (band IN ('TAKE_OFFLINE', 'PR_ONLY', 'DIGEST', 'NONE')),
    explanation     text,                                              -- Risk Scoring agent, in business terms
    remediation     jsonb,                                             -- RemediationResult: target_version, fix_verified, docker_tag_verified, files_changed, pr_url, notes
    pr_url          text,
    -- OPEN (scored, acting) | MITIGATED (risk contained, e.g. service offline) | RESOLVED (patched version running)
    status          text NOT NULL DEFAULT 'OPEN'
                    CHECK (status IN ('OPEN', 'MITIGATED', 'RESOLVED')),
    created_at      timestamptz NOT NULL DEFAULT now(),
    mitigated_at    timestamptz,                                       -- time to mitigate = mitigated_at - created_at
    resolved_at     timestamptz,
    UNIQUE (component, service_id)
);

CREATE INDEX incidents_service_idx ON incidents (service_id);


-- Dashboard lanes: one row per (component, agent, service), upserted by DashboardHooks with
-- ON CONFLICT (component, agent, service) DO UPDATE (NULLs compare equal here).
CREATE TABLE agent_runs (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    component  text,                           -- 'php'; NULL for the feed-level Triage run
    agent      text NOT NULL
               CHECK (agent IN ('triage', 'threat_intel', 'risk_scoring', 'containment', 'remediation')),
    service    text,                           -- services.name; NULL for triage and threat_intel
    -- idle (lane shown, not started) | running | done | failed | cached (intel served from cache or fixture)
    status     text NOT NULL DEFAULT 'idle'
               CHECK (status IN ('idle', 'running', 'done', 'failed', 'cached')),
    last_tool  text,                           -- latest tool call, e.g. 'fetch_page_content(php.net/archive/2026.php)'
    started_at timestamptz,
    ended_at   timestamptz,
    output     jsonb,                          -- the agent's Pydantic output (model_dump(mode='json'))
    error      text,                           -- set with status 'failed'
    CONSTRAINT agent_runs_lane_key UNIQUE NULLS NOT DISTINCT (component, agent, service)
);


-- Dashboard trace, append-only; order by id. agent NULL = Sentinel itself (feed, scanner, orchestrator).
CREATE TABLE agent_log (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    component text,                            -- 'php'; NULL for feed and scanner lines
    agent     text CHECK (agent IN ('triage', 'threat_intel', 'risk_scoring', 'containment', 'remediation')),
    service   text,                            -- services.name for per-service lanes, else NULL
    level     text NOT NULL DEFAULT 'info'
              CHECK (level IN ('info', 'warn', 'error', 'success')),
    message   text NOT NULL,                   -- e.g. 'Threat Intel -> fetch_page_content(php.net/archive/2026.php)'
    ts        timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX agent_log_lane_idx ON agent_log (component, agent, service, id DESC);


-- Feed funnel for the dashboard. 21 Oct replay: total 544, keyword_hits 40, matched 2, matched_components 1.
CREATE VIEW feed_funnel AS
SELECT count(*)::int                                                           AS total,
       count(*) FILTER (WHERE keyword_match)::int                              AS keyword_hits,
       count(*) FILTER (WHERE triage_status = 'NEW')::int                      AS untriaged,
       count(*) FILTER (WHERE triage_status = 'CANDIDATE')::int                AS candidates,
       count(*) FILTER (WHERE triage_status = 'DISMISSED')::int                AS dismissed,
       count(*) FILTER (WHERE triage_status = 'MATCHED')::int                  AS matched,
       count(DISTINCT component) FILTER (WHERE triage_status = 'MATCHED')::int AS matched_components
FROM cve_events;

COMMIT;
