-- Adds the runs and chat_messages tables to an existing Guard database without touching its data.
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f sentinel/db/migrations/002_runs_chat.sql

SET client_min_messages = warning;

CREATE TABLE IF NOT EXISTS runs (
    id         text PRIMARY KEY,
    title      text NOT NULL,
    status     text NOT NULL DEFAULT 'live' CHECK (status IN ('live', 'archived')),
    outcome    text,
    started_at timestamptz NOT NULL DEFAULT now(),
    ended_at   timestamptz
);

CREATE TABLE IF NOT EXISTS chat_messages (
    id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id text NOT NULL REFERENCES runs (id) ON DELETE CASCADE,
    role   text NOT NULL CHECK (role IN ('guard', 'user', 'event')),
    text   text NOT NULL,
    card   jsonb,
    ts     timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX IF NOT EXISTS chat_messages_run_idx ON chat_messages (run_id, id);
